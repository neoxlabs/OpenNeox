/**
 * Get the best logo variant based on terminal width
 */
export function getNeoxLogo(terminalWidth?: number): string {
  const width = terminalWidth || process.stdout.columns || 80;

  if (width < 60) {
    return neoxAsciiLogoSmall;
  } else if (width < 80) {
    return neoxAsciiLogoCompact;
  } else {
    return neoxAsciiLogo;
  }
}
