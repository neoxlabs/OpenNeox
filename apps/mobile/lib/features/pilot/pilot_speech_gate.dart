/// pilot_speech_gate.dart — 念稿的「这一轮还算不算数」(pilot:U-20)。
///
/// 手机上的念稿不是「点一下就出声」: 先把文字合成成音频 (订阅网关 / 阿里云 / 本地模型,
/// 几百毫秒到几秒), 再交给原生播放器播。用户点停时, 手上这句可能还在合成,
/// 后面还排着一两句 —— 只停原生播放器, 合成完的会接着开口, 排队的下一句也会开口,
/// 用户的感觉就是「停不下来, 只能杀 App」。
///
/// 所以每一轮念稿先领一个 epoch; 点停 / 开新一轮都让 epoch 往前走一步。
/// 合成回来、播放之前拿 epoch 对一下: 对不上就不出声。凭证是纯数据, 没有平台依赖, 可以直接测。
class PilotSpeechGate {
  int _epoch = 0;

  /// 当前这一轮的凭证
  int get epoch => _epoch;

  /// 开新一轮: 上一轮没念完的作废 (它已经有新的话要说)
  int begin() => ++_epoch;

  /// 用户点停 (或离开这一页): 在途合成与排队待播的一并作废
  int interrupt() => ++_epoch;

  /// [token] 这一轮还能不能出声
  bool open(int token) => token == _epoch;
}
