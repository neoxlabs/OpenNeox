/// image_charge_policy.dart — 出图失败时能不能重试 / 换路的计费安全规则 (chat:C4-02).
///
/// 只按一件事分级: **这次失败时, 钱有没有可能已经扣了**。
///   · 网关在受理前就拒掉的 4xx — 请求没进上游出图队列, 肯定没扣费;
///     其中只有 429 限流值得原路重试一次 (见 [isWorthRetrying]), 仍失败再退到
///     用户自己配的 Key 出图; 402 / 403 / 400 这类确定性错误直接走下一步。
///   · 5xx / 超时 / 已经提交成任务的失败 (202 之后任务失败) — 可能已受理扣费;
///     一律不重试、不换路, 如实报错。
library;

/// 「明确没扣费」的失败在原路重试一次的间隔.
const imageRetryDelay = Duration(seconds: 2);

/// 这个 HTTP 状态码是否属于「网关在受理前拒掉, 肯定没扣费」.
///
/// 只认 4xx, 且排除:
///   · 408 (请求超时) — 服务端可能已经开始处理, 结果未知;
///   · 408 之外的所有非 4xx (5xx / 2xx 回包里的任务失败) — 可能已扣费。
bool isDefinitelyNotCharged(int status) =>
    status >= 400 && status < 500 && status != 408;

/// 没扣费的失败里, 只有「临时性」的才值得原路再试 (现在只有 429 限流)。
/// 402 额度不足 / 403 无权益 / 400 参数错这类确定性错误, 再试一次结果一样,
/// 直接走下一步 (退 BYOK 或报错), 不白等 2 秒。
bool isWorthRetrying(int status) => status == 429;
