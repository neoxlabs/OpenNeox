/**
 * bake-chat-persona.mjs — Chat 档人设的单一源 → 两端常量 (chat:C2-05)
 *
 * 背景: 手机 (apps/mobile/lib/core/local_agent/chat_light_prompt.dart) 和桌面
 * (packages/core/src/runtime/prompts/chatLightPrompt.ts) 各写过一份聊天人设, 一句改了一边、
 * 另一边没改, 用户看到的就是「一个像朋友、一个像客服」。
 *
 * 单一真相源 = chatPersona.source.json (人类可编辑), 本脚本把**所有组合**
 * (语言 × 有没有搜索 × 有没有画图 × 来源怎么给) 都拼好, 一次生成两个文件:
 *   · packages/core/src/runtime/prompts/chatPersona.generated.ts  (桌面)
 *   · apps/mobile/lib/core/local_agent/chat_persona.g.dart        (手机)
 * 两端只按 key 取字符串, 不再各自拼装 —— 拼装逻辑只在这里一份。
 *
 * 用法:
 *   node scripts/bake-chat-persona.mjs          重写两个生成文件
 *   node scripts/bake-chat-persona.mjs --check  只比对, 不同步就 exit 1 (CI / 测试用)
 *
 * 两端的测试会把生成结果跟源 JSON 重新拼一遍比对: 改了源忘了跑本脚本 → 测试红。
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'packages/core/src/runtime/prompts/chatPersona.source.json';
const TS_OUT = 'packages/core/src/runtime/prompts/chatPersona.generated.ts';
const DART_OUT = 'apps/mobile/lib/core/local_agent/chat_persona.g.dart';

const LANGS = ['zh', 'en'];
const STYLES = ['card', 'links'];

/** 行尾统一 LF —— 这些文本原样进 system 段, 两边构建必须逐字节一致。 */
function readText(rel) {
  return readFileSync(join(REPO_ROOT, rel), 'utf-8').replace(/\r\n/g, '\n');
}

/** 按可用工具拼一份人设。顺序固定: 人格段 → 工具表 → 缺件说明 → 收尾 → 边界。 */
export function composePersona(src, lang, { search, image }, style) {
  const l = src[lang];
  const lines = [l.core];
  const count = (search ? 1 : 0) + (image ? 1 : 0);
  lines.push(l.toolsHeader[String(count)]);
  if (search) lines.push(l.tool.search);
  if (image) lines.push(l.tool.image);
  if (!search) lines.push(l.missing.search);
  if (!image) lines.push(l.missing.image);
  if (count === 0) lines.push(l.missing.none);
  if (search && style === 'links') lines.push(l.closing.links);
  else if (count > 0) lines.push(l.closing.card);
  lines.push(l.noFiles);
  return lines.join('\n');
}

export function personaKey(lang, { search, image }, style) {
  return `${lang}|${search ? 1 : 0}${image ? 1 : 0}|${style}`;
}

/** 源 JSON → { sha, entries: [[key, text], ...] } */
export function buildPersonas() {
  const raw = readText(SOURCE);
  const src = JSON.parse(raw);
  const sha = createHash('sha256').update(raw, 'utf-8').digest('hex');
  const entries = [];
  for (const lang of LANGS) {
    for (const search of [true, false]) {
      for (const image of [true, false]) {
        for (const style of STYLES) {
          entries.push([
            personaKey(lang, { search, image }, style),
            composePersona(src, lang, { search, image }, style),
          ]);
        }
      }
    }
  }
  return { sha, entries, src };
}

function tsQuote(s) {
  return JSON.stringify(s).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
}

function dartQuote(s) {
  return `'${s
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\$/g, '\\$')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')}'`;
}

export function renderTs({ sha, entries }) {
  const banner = [
    '/**',
    ' * AUTO-GENERATED by scripts/bake-chat-persona.mjs — 请勿手改。',
    ` * 源: ${SOURCE}`,
    ' * 改人设请改源 JSON 再跑: node scripts/bake-chat-persona.mjs',
    ' *',
    ' * key = `语言|搜索+画图|来源方式` (11 = 两件都有, 10 = 只有搜索, 01 = 只有画图, 00 = 都没有)。',
    ' */',
    '',
    'export type ChatPersonaStyle = \'card\' | \'links\';',
    '',
    `export const CHAT_PERSONA_SOURCE_SHA = '${sha}';`,
    '',
    '/** 变体 key —— 两端用同一个拼法, 不许各写一份。 */',
    'export function chatPersonaKey(',
    '  lang: string,',
    '  search: boolean,',
    '  image: boolean,',
    '  style: ChatPersonaStyle,',
    '): string {',
    '  return `${lang}|${search ? 1 : 0}${image ? 1 : 0}|${style}`;',
    '}',
    '',
    'export const CHAT_PERSONAS: Readonly<Record<string, string>> = {',
  ];
  for (const [key, text] of entries) banner.push(`  ${tsQuote(key)}: ${tsQuote(text)},`);
  banner.push('};', '');
  return banner.join('\n');
}

export function renderDart({ sha, entries }) {
  const out = [
    '// AUTO-GENERATED by scripts/bake-chat-persona.mjs — 请勿手改。',
    `// 源: ${SOURCE}`,
    '// 改人设请改源 JSON 再跑: node scripts/bake-chat-persona.mjs',
    '// key = `语言|搜索+画图|来源方式` (11 = 两件都有, 10 = 只有搜索, 01 = 只有画图, 00 = 都没有)。',
    'library;',
    '',
    `const String kChatPersonaSourceSha = '${sha}';`,
    '',
    '/// 变体 key —— 两端用同一个拼法, 不许各写一份。',
    'String chatPersonaKey(',
    '  String lang, {',
    '  required bool search,',
    '  required bool image,',
    "  required String style,",
    '}) =>',
    "    '$lang|${search ? 1 : 0}${image ? 1 : 0}|$style';",
    '',
    'const Map<String, String> kChatPersonas = <String, String>{',
  ];
  for (const [key, text] of entries) out.push(`  ${dartQuote(key)}: ${dartQuote(text)},`);
  out.push('};', '');
  return out.join('\n');
}

export function renderAll() {
  const built = buildPersonas();
  return {
    [TS_OUT]: renderTs(built),
    [DART_OUT]: renderDart(built),
  };
}

function main() {
  const check = process.argv.includes('--check');
  const outputs = renderAll();
  let drifted = false;
  for (const [rel, content] of Object.entries(outputs)) {
    const path = join(REPO_ROOT, rel);
    let current = null;
    try {
      current = readFileSync(path, 'utf-8');
    } catch { /* 还没生成过 */ }
    if (check) {
      if (current !== content) {
        drifted = true;
        console.error(`[bake-chat-persona] 过期: ${rel} —— 跑一次 node scripts/bake-chat-persona.mjs`);
      }
      continue;
    }
    if (current !== content) writeFileSync(path, content, 'utf-8');
    console.log(`[bake-chat-persona] ${rel}`);
  }
  if (drifted) process.exit(1);
  if (check) console.log('[bake-chat-persona] 生成文件与源一致。');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
