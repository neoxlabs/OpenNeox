/** 一页讲稿: 按换行切段落 */
export function writeNotesSlideXml(notes: string): string {
  const paras = String(notes).split(/\r?\n/).map((line) =>
    line.trim() ? `<a:p><a:r><a:rPr lang="zh-CN" dirty="0"/><a:t>${esc(line)}</a:t></a:r></a:p>` : '<a:p><a:endParaRPr lang="zh-CN"/></a:p>',
  ).join('');
  return `${XML_DECL}
<p:notes ${NS}>
  <p:cSld>
    <p:spTree>${GRP}
      <p:sp><p:nvSpPr><p:cNvPr id="2" name="Slide Image Placeholder 1"/><p:cNvSpPr><a:spLocks noGrp="1" noRot="1" noChangeAspect="1"/></p:cNvSpPr><p:nvPr><p:ph type="sldImg"/></p:nvPr></p:nvSpPr><p:spPr/></p:sp>
      <p:sp><p:nvSpPr><p:cNvPr id="3" name="Notes Placeholder 2"/><p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr><p:nvPr><p:ph type="body" idx="1"/></p:nvPr></p:nvSpPr><p:spPr/><p:txBody><a:bodyPr/><a:lstStyle/>${paras || '<a:p><a:endParaRPr lang="zh-CN"/></a:p>'}</p:txBody></p:sp>
    </p:spTree>
  </p:cSld>
  <p:clrMapOvr><a:masterClrMapping/></p:clrMapOvr>
</p:notes>`;
}

export function writeNotesSlideRelsXml(slideNum: number): string {
  return `${XML_DECL}
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/notesMaster" Target="../notesMasters/notesMaster1.xml"/>
  <Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slide" Target="../slides/slide${slideNum}.xml"/>
</Relationships>`;
}

/** 这页有没有要写的讲稿 */
export function hasNotes(s: { notes?: string }): boolean {
  return typeof s.notes === 'string' && s.notes.trim().length > 0;
}
