import { describe, expect, it } from 'vitest';

import { plain } from '../report';

describe('plain —— 我们自己要加粗的那几行', () => {
  it('剥掉模型自带的 ** —— 否则渲染层再包一层就是四颗裸星号 (实拍)', () => {
    expect(plain('**截至 9 月 13 日，还没有人真正评测过**')).toBe('截至 9 月 13 日，还没有人真正评测过');
  });

  it('行内嵌的加粗也剥 —— 整行本来就要加粗, 再嵌一层没有意义', () => {
    expect(plain('机构预测差 **7 倍**，但份额是共识')).toBe('机构预测差 7 倍，但份额是共识');
  });

  it('cid 照样剥干净', () => {
    expect(plain('**共识只有三条 [C271][C444]**')).toBe('共识只有三条');
  });

  it('__ 下划线式加粗同样处理', () => {
    expect(plain('__两边引用的是同一批素材__')).toBe('两边引用的是同一批素材');
  });

  it('⚠️ 不碰正常文本', () => {
    expect(plain('折叠屏只占全球销量约 2%~3%')).toBe('折叠屏只占全球销量约 2%~3%');
  });
});
